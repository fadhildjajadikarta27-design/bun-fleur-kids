CREATE TABLE IF NOT EXISTS public.birthday_prices (
 product_id text PRIMARY KEY CHECK (product_id IN ('poster','papercraft','placemat','celengan','puzzle','growthchart','tshirt')),
 price integer NOT NULL CHECK (price BETWEEN 1000 AND 10000000)
);
CREATE TABLE IF NOT EXISTS public.birthday_events (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code text NOT NULL UNIQUE, owner_id text NOT NULL, request_key text NOT NULL UNIQUE,
 event_name text NOT NULL, child_age integer NOT NULL CHECK(child_age BETWEEN 1 AND 18),
 event_date text NOT NULL, deadline text NOT NULL, theme text NOT NULL,
 guest_count integer NOT NULL CHECK(guest_count BETWEEN 20 AND 500),
 items jsonb NOT NULL CHECK(jsonb_typeof(items)='array' AND jsonb_array_length(items) BETWEEN 1 AND 7),
 per_guest integer NOT NULL CHECK(per_guest > 0), total integer NOT NULL CHECK(total = per_guest * guest_count AND total > 0),
 organizer text NOT NULL, whatsapp text NOT NULL, address text NOT NULL, notes text NOT NULL,
 status text NOT NULL DEFAULT 'requested' CHECK(status IN ('requested','confirmed','paid','production','shipped','completed','cancelled','refunded')),
 payment_reference text UNIQUE, tracking_number text NOT NULL DEFAULT '',
 created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS birthday_events_owner_idx ON public.birthday_events(owner_id, created_at DESC);
