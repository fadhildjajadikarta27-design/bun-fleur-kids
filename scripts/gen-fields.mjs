// Generates client/src/fields.ts (run with bun: `bun run gen:fields`).
//
// The Space runtime had a Bun macro, actionFields<typeof Actions>(), that
// derived HTML input attributes from each action's zod request schema and
// let components write {...FIELDS.createOrder.customerName} on <input>s.
// This script reproduces that mapping ahead of time: it introspects every
// action's request schema via z.toJSONSchema() and emits a plain data
// module the Vite client can import.
//
// Mapping (per request field):
//   string with format "email"  → { type: "email" } (+ length bounds)
//   string with min/maxLength   → { minLength?, maxLength? }
//   number/integer with bounds  → { min?, max? }
//   anything else               → {}

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import { Actions } from "../server/src/actions.ts";

function attrsFor(sch) {
  if (!sch || typeof sch !== "object") return {};
  const attrs = {};
  if (sch.format === "email") attrs.type = "email";
  if (sch.type === "string") {
    if (typeof sch.maxLength === "number") attrs.maxLength = sch.maxLength;
    if (typeof sch.minLength === "number" && sch.minLength > 0) attrs.minLength = sch.minLength;
  }
  if (sch.type === "number" || sch.type === "integer") {
    // zod encodes .int() as a ±Number.MAX_SAFE_INTEGER bound in JSON
    // Schema — that is a type sentinel, not a real input constraint.
    if (typeof sch.minimum === "number" && sch.minimum !== -Number.MAX_SAFE_INTEGER) attrs.min = sch.minimum;
    if (typeof sch.maximum === "number" && sch.maximum !== Number.MAX_SAFE_INTEGER) attrs.max = sch.maximum;
  }
  return attrs;
}

const fields = {};
for (const [name, def] of Object.entries(Actions)) {
  const jsonSchema = z.toJSONSchema(def.request);
  const props = jsonSchema.properties ?? {};
  const entry = {};
  for (const [field, sch] of Object.entries(props)) {
    entry[field] = attrsFor(sch);
  }
  fields[name] = entry;
}

const out = `// Generated by scripts/gen-fields.mjs from the actions' zod request
// schemas — do not edit by hand; run \`bun run gen:fields\` after changing
// a request schema in server/src/actions.ts.
//
// Replaces the Space runtime's actionFields() Bun macro: each entry holds
// the HTML input attributes for one action request field, spread onto
// <input> elements as {...FIELDS.createOrder.customerName}.

import type { Actions } from "../../server/src/actions";
import type { z } from "zod";

export interface FieldAttrs {
  type?: string;
  maxLength?: number;
  minLength?: number;
  min?: number;
  max?: number;
}

type FieldsShape<A> = {
  [K in keyof A]: A[K] extends { request: infer Req extends z.ZodType }
    ? { [F in keyof z.input<Req>]: FieldAttrs }
    : Record<string, FieldAttrs>;
};

export const FIELDS: FieldsShape<typeof Actions> = ${JSON.stringify(fields, null, 2)};
`;

const target = join(dirname(fileURLToPath(import.meta.url)), "..", "client", "src", "fields.ts");
writeFileSync(target, out);
console.log(`Wrote ${target} (${Object.keys(fields).length} actions)`);
