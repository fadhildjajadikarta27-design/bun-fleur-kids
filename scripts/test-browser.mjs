  await page.goto(base+"/#/kreasiku");
  await artwork.getByRole("button",{name:"Jadikan Nyata — Pesan Produk"}).click();
  async function addProduct(name){
    const card=page.locator("article").filter({has:page.getByRole("heading",{name,exact:true})});
    await card.getByRole("button",{name:"Pilih & Tambah ke Keranjang"}).click();
    await page.getByRole("button",{name:"Tambah ke Keranjang",exact:true}).click();
  }
  await addProduct("Poster");
  await addProduct("Papercraft 3D");
  await page.getByRole("button",{name:"Lihat Keranjang",exact:true}).click();
  await page.getByRole("heading",{name:"Keranjang & Pemesanan (2)"}).waitFor();
  await page.getByText("Paket Little Artist aktif",{exact:false}).waitFor();
  await page.reload();
  await page.getByRole("button",{name:"Lanjutkan Keranjang (2)"}).click();
  await page.getByRole("heading",{name:"Keranjang & Pemesanan (2)"}).waitFor();
  await page.getByText("Paket Little Artist aktif",{exact:false}).waitFor();
  await page.locator("#co-name").fill("QA Browser Parent");
  await page.locator("#co-wa").fill("081299990001");
  await page.locator("#co-email").fill("qa-browser@example.test");
  await page.locator("#co-address").fill("Alamat QA browser Jakarta Indonesia");
  await page.getByRole("checkbox",{name:"Jadikan hadiah"}).check();
  await page.getByLabel("Nama pengirim",{exact:true}).fill("QA Pengirim");
  await page.getByLabel("Nama penerima",{exact:true}).fill("QA Penerima");
  await page.getByLabel("Kartu ucapan",{exact:true}).fill("Selamat ulang tahun!");
  const responsePromise=page.waitForResponse(res=>res.url().endsWith("/api/actions")&&res.request().postDataJSON()?.action==="createOrder");
  await page.getByRole("button",{name:"Buat Pesanan",exact:true}).click();
  const response=await responsePromise;
  assert.equal(response.status(),200,await response.text());
  const order=(await response.json()).order;
  assert.equal(order.bundleName,"Little Artist");
  assert.equal(order.total,64900);
  assert.equal(order.items.length,2);
  assert.equal(order.gift.recipient,"QA Penerima");
  console.log("PASS mobile two-product cart, reload restore, bundle, gift and checkout");
  await page.goto(base+"/#/birthday");
  await page.getByLabel("Nama acara",{exact:true}).fill("QA Browser Birthday");
  const date=new Date();date.setUTCDate(date.getUTCDate()+40);
  await page.getByLabel("Tanggal acara",{exact:true}).fill(date.toISOString().slice(0,10));
  await page.getByLabel("Tema acara",{exact:true}).fill("Dino");
  await page.getByLabel("Nama orang tua / penyelenggara",{exact:true}).fill("QA Browser");
